Handler = Callable[[list[str], Request], list[ResultBlock] | LongRunningResult]


@dataclass(frozen=True)
class CommandSpec:
    path: tuple[str, ...]
    object_type: str
    summary: str
    credential: str
    handler: Handler


def _spec(path: str, object_type: str, summary: str, credential: str, handler: Handler) -> CommandSpec:
    return CommandSpec(tuple(path.split()), object_type, summary, credential, handler)


