COMMANDS_BY_PATH = {spec.path: spec for spec in COMMANDS}


def match_command(argv: list[str]) -> tuple[CommandSpec | None, list[str]]:
    best: CommandSpec | None = None
    best_len = 0
    for spec in COMMANDS:
        n = len(spec.path)
        if len(argv) >= n and tuple(argv[:n]) == spec.path and n > best_len:
            best = spec
            best_len = n
    if best is None:
        return None, argv
    return best, argv[best_len:]
